#!/usr/bin/env bash
# Dependency license audit: build docs/LICENSES.md from the pinned
# dependency tree and fail on licenses outside the allowlist.
#
# Usage: scripts/license-audit.sh            # regenerate docs/LICENSES.md
#        scripts/license-audit.sh --check     # CI mode: no writes, exit 1 on REVIEW
set -u
cd "$(dirname "$0")/.." || exit 1

CHECK=0
if [ "${1:-}" = "--check" ]; then CHECK=1; fi

# SPDX allowlist: permissive + font data licenses. Anything else (GPL, AGPL,
# or unknown) is a review gate.
#
# MPL-2.0 is accepted for one audited case: `option-ext` (transitive
# dependency of the path-resolution crate `dirs`). MPL-2.0 is file-scoped
# copyleft (modifications to that file stay MPL; the rest of the binary is
# unaffected), so it is cleared for a CLI tool.
#
# The allowlist is the single source of truth inside the python block below.

cargo metadata --format-version 1 >/dev/null 2>&1 || { echo "cargo metadata failed"; exit 2; }

out=docs/LICENSES.md
gen=$(mktemp)
{
    echo "# Dependency licenses"
    echo
    echo "Generated by \`scripts/license-audit.sh\` from \`cargo metadata\` on $(date +%Y-%m-%d)."
    echo "Every dependency in \`Cargo.lock\` is listed; direct dependencies are marked \`(*)\`."
    echo
} > "$gen"

python3 - <<'EOF' >> "$gen"
import json, sys, subprocess

m = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1"], text=True))
pkgs = m["packages"]
direct = set(f'{p["name"]} {p["version"]}' for p in pkgs if not p.get("source"))

allow = set("""MIT Apache-2.0 Apache-1.1 BSD-2-Clause BSD-3-Clause ISC Unicode-3.0 Unicode-DFS-2016 Zlib CC0-1.0 MPL-2.0 NCSA Unlicense""".split())

print("| package | version | license | kind |")
print("|---------|---------|---------|------|")
bad = 0
for p in sorted(pkgs, key=lambda x: (x["name"], x["version"])):
    lic = (p.get("license") or "unknown").strip() or "unknown"
    mark = "(*)" if f'{p["name"]} {p["version"]}' in direct else "transitive"
    ok = "" if any(a in lic for a in allow) else " **REVIEW**"
    if ok:
        bad += 1
    print(f'| {p["name"]} | {p["version"]} | {lic} | {mark}{ok} |')
print()
print(f"{bad} package(s) require manual review.")
sys.exit(1 if bad else 0)
EOF
status=$?
rc=$status

if [ "$CHECK" = "1" ]; then
    # CI mode: no writes — the gate is the allowlist count.
    if [ $status -eq 0 ]; then
        echo "license audit (check mode): all dependencies on the allowlist"
    else
        echo "license audit (check mode): a dependency requires review — run without --check to inspect"
    fi
else
    cp "$gen" "$out"
    echo "wrote $out"
    [ $status -eq 0 ] && echo "license audit: all dependencies on the allowlist"
fi
rm -f "$gen"
exit $rc
